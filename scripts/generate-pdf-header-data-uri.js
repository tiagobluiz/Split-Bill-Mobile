const fs = require("fs");
const path = require("path");
const Jimp = require("jimp-compact");

const ROOT = path.resolve(__dirname, "..");
const SOURCE = path.join(ROOT, "assets", "split-bill-pdf-header.png");
const OUTPUT = path.join(ROOT, "src", "pdf", "pdfHeaderImageDataUri.generated.ts");
const TARGET_WIDTH = 1086;
async function main() {
  const image = await Jimp.read(SOURCE);
  if (image.bitmap.width > TARGET_WIDTH) {
    image.resize(TARGET_WIDTH, Jimp.AUTO);
  }

  const buffer = await image.getBufferAsync(Jimp.MIME_PNG);
  const base64 = buffer.toString("base64");
  const dataUri = `data:image/png;base64,${base64}`;

  const output = `// This file is generated by scripts/generate-pdf-header-data-uri.js. Do not edit by hand.\n\nexport const PDF_HEADER_IMAGE_DATA_URI = ${JSON.stringify(dataUri)};\n`;

  fs.writeFileSync(OUTPUT, output);
  console.log(`Generated ${path.relative(ROOT, OUTPUT)} from ${path.relative(ROOT, SOURCE)} (${image.bitmap.width}x${image.bitmap.height}, ${buffer.length} bytes).`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
